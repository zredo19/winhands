"""Build winhands/exo/ui/exo-mascot.js from the Claude Design export of the Exo character (Exo.dc.html).

    python tools/exo_mascot_build.py "<export folder>/Exo.dc.html"

The design component renders with React.createElement inside a Claude Design runtime; this wraps its script
with a tiny createElement that builds SVG DOM directly, so the widget needs neither React nor the runtime.
"""
import html, pathlib, re, sys

OUT = pathlib.Path(__file__).resolve().parents[1] / "winhands" / "exo" / "ui" / "exo-mascot.js"

PRELUDE = r"""// Generated by tools/exo_mascot_build.py from the Claude Design export (Exo.dc.html). Do not edit by hand.
(() => {
const NS = "http://www.w3.org/2000/svg";
const CAMEL = new Set(["viewBox", "preserveAspectRatio", "gradientUnits", "gradientTransform", "stdDeviation",
  "patternUnits", "clipPathUnits", "textLength", "lengthAdjust", "spreadMethod", "maskUnits"]);
const attr = k => k === "className" ? "class" : k === "xlinkHref" ? "href" : CAMEL.has(k) ? k
  : k.replace(/[A-Z]/g, c => "-" + c.toLowerCase());
function createElement(tag, props, ...kids) {
  const el = document.createElementNS(NS, tag);
  for (const [k, v] of Object.entries(props || {})) {
    if (v == null || v === false || k === "key" || k === "children") continue;
    if (k === "style") { for (const [s, sv] of Object.entries(v)) if (sv != null) el.style[s] = sv; }
    else el.setAttribute(attr(k), v === true ? "" : v);
  }
  const add = c => {
    if (c == null || c === false || c === true) return;
    if (Array.isArray(c)) c.forEach(add);
    else el.appendChild(c instanceof Node ? c : document.createTextNode(String(c)));
  };
  kids.forEach(add);
  return el;
}
const React = { createElement };
class DCLogic { constructor(props) { this.props = props || {}; } }
"""

POSTLUDE = r"""
const STATES = ["idle", "listening", "thinking", "working", "speaking", "success", "error", "sleeping"];
let root = null, props = { state: "idle", view: "front", size: 190, detail: "auto", fold: 0, theme: "dark" };
let comp = null, raf = 0;
function render() {
  if (!root) return;
  comp = comp || new Component(props);
  comp.props = props;
  root.replaceChildren(comp.renderVals().svg);
}
function animateFold(from, to, ms, done) {
  cancelAnimationFrame(raf);
  const t0 = performance.now();
  const step = t => {
    const k = Math.min(1, (t - t0) / ms), e = 1 - Math.pow(1 - k, 4);
    props = { ...props, fold: from + (to - from) * e };
    render();
    if (k < 1) raf = requestAnimationFrame(step); else done && done();
  };
  raf = requestAnimationFrame(step);
}
window.ExoMascot = {
  states: STATES,
  mount(el, opts) { root = el; props = { ...props, ...(opts || {}) }; render(); },
  setState(name) {
    const s = STATES.includes(name) ? name : "idle";
    if (s !== props.state) { props = { ...props, state: s }; render(); }
  },
  setLevel() {},                      // the design animates speech on its own
  transformIn(ms = 1400) { animateFold(1, 0, ms); },
  dock(ms = 900) { return new Promise(r => animateFold(props.fold, 1, ms, r)); },
};
})();
"""


def build(src):
    text = pathlib.Path(src).read_text(encoding="utf-8")
    m = re.search(r'<script type="text/x-dc"[^>]*>(.*?)</script>', text, re.S)
    if not m:
        raise SystemExit("no x-dc script found: is this a Claude Design component export?")
    body = html.unescape(m.group(1)) if "&lt;" in m.group(1) else m.group(1)
    if "class Component extends DCLogic" not in body or "renderVals" not in body:
        raise SystemExit("unexpected component shape (needs class Component extends DCLogic with renderVals)")
    OUT.write_text(PRELUDE + body + POSTLUDE, encoding="utf-8")
    return OUT


if __name__ == "__main__":
    print("wrote", build(sys.argv[1]))
